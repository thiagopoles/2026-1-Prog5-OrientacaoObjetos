
public class Veiculo {
	private String motor;
	private int peso;
	public Veiculo(String motor, int peso) {
		super();
		this.motor = motor;
		this.peso = peso;
	}
	public String getMotor() {
		return motor;
	}
	public void setMotor(String motor) {
		this.motor = motor;
	}
	public int getPeso() {
		return peso;
	}
	public void setPeso(int peso) {
		this.peso = peso;
	}
	
}
